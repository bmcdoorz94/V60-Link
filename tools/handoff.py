#!/usr/bin/env python3
"""Generate HANDOFF.md: a single, complete Markdown package of the V60 Garage project for another AI (Claude <-> Gemini).

Usage: python3 tools/handoff.py [output_path]      (default: HANDOFF.md in the repo root, gitignored)

Sections 1-3 come from docs/HANDOFF_STATE.md (update it before running). Section 4 is every source file, written
out by this script byte for byte, so nothing can be truncated. Build outputs (root index.html, js/, dist-artifact/,
link.html, sw.js) are left out on purpose: tools/build.py regenerates them from src/, and including both copies
invites edits to the wrong one.
"""
import base64, datetime, hashlib, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEXT_DIRS = ["src", "tools", "tests", "docs", ".github"]
TEXT_TOP = ["CLAUDE.md", "README.md", ".gitignore", ".nojekyll"]
BINARY = ["icons/icon-180.png", "icons/icon-192.png", "icons/icon-512.png"]
LANG = {".js": "javascript", ".css": "css", ".html": "html", ".py": "python", ".md": "markdown", ".yml": "yaml", ".json": "json"}

def sh(*a):
    try: return subprocess.check_output(a, cwd=ROOT, text=True).strip()
    except Exception: return "unknown"

def files():
    out = []
    for top in TEXT_TOP:
        if os.path.isfile(os.path.join(ROOT, top)): out.append(top)
    for d in TEXT_DIRS:
        for base, dirs, fs in os.walk(os.path.join(ROOT, d)):
            dirs[:] = sorted(x for x in dirs if x not in ("shots", "__pycache__", "node_modules"))
            for f in sorted(fs):
                p = os.path.relpath(os.path.join(base, f), ROOT).replace(os.sep, "/")
                if p == "docs/HANDOFF_STATE.md": continue  # already inlined as sections 1-3
                out.append(p)
    return out

def fence_for(text):
    longest = max([len(m) for m in re.findall(r"`+", text)] + [2])
    return "`" * max(3, longest + 1)

def main():
    dest = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "HANDOFF.md")
    state = open(os.path.join(ROOT, "docs", "HANDOFF_STATE.md"), encoding="utf-8").read().strip()
    fl = files()
    rows, blocks, total = [], [], 0
    for p in fl:
        data = open(os.path.join(ROOT, p), "rb").read()
        text = data.decode("utf-8")
        total += len(data)
        rows.append("| `%s` | %d | %d | `%s` |" % (p, text.count("\n") + (0 if text.endswith("\n") or not text else 1), len(data), hashlib.sha256(data).hexdigest()[:12]))
        f = fence_for(text)
        blocks.append("### `%s`\n\n%s%s\n%s%s%s\n" % (p, f, LANG.get(os.path.splitext(p)[1], ""), text, "" if text.endswith("\n") or not text else "\n", f))
    bins = []
    for p in BINARY:
        fp = os.path.join(ROOT, p)
        if not os.path.isfile(fp): continue
        data = open(fp, "rb").read()
        rows.append("| `%s` (binary, base64) | - | %d | `%s` |" % (p, len(data), hashlib.sha256(data).hexdigest()[:12]))
        bins.append("### `%s` (base64)\n\n```base64\n%s\n```\n" % (p, "\n".join(re.findall(".{1,100}", base64.b64encode(data).decode()))))
    now = datetime.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M %Z")
    doc = """# V60 Garage — Handoff Package

Generated %s from commit `%s` (%s). Version live at that commit: `%s`.

- Repo (source of truth): https://github.com/bmcdoorz94/V60-Link (branch `main`)
- Live app: https://bmcdoorz94.github.io/V60-Link/
- Files in section 4: %d text files and %d binary files, %s bytes of text. Each file has a SHA-256 prefix in the manifest so the receiver can confirm it is complete.

## 0. Rules for the receiving AI
1. Read `CLAUDE.md` in section 4 first. It holds the project rules: sourcing, accuracy, file layout, UI conventions and the privacy rule (never write the VIN, plate or chassis number into any file).
2. Kyle directs the work and does not write code. Explain changes in plain words, ask him clarifying questions before or while working, and cite real sources for any car fact.
3. Edit only source files: `src/`, `tools/`, `tests/`, `docs/`, `CLAUDE.md`. The live site's `index.html`, `js/`, `sw.js` and `dist-artifact/` are generated by `python3 tools/build.py`. A GitHub Action (`.github/workflows/build.yml`) runs that build automatically when `src/` or `tools/` change on `main`.
4. `src/js/modules/live.js` is generated by `python3 tools/gen/mklive.py` from `tools/gen/live_extra.js` and `src/link-legacy.html`. Edit those, not live.js.
5. New features go in a new file in `src/js/modules/` (see the module contract in CLAUDE.md), added to `MODULES` in `tools/build.py`.

## Return format (when handing back)
Produce one Markdown file containing:
- Updated sections 1, 2 and 3 using the same headings.
- Under `## 4. Complete Codebase`, every file you created or changed, each as `### \\`path/from/repo/root\\`` followed by one fenced code block with the **entire** file. Never truncate, never write "unchanged" or "rest of file", never use placeholders.
- Files you did not touch may be left out of a return package. `tools/apply_handoff.py` overlays the files present onto the repo. To delete a file, list it under `## Deleted files` as a bullet with its path in backticks.
- If a full copy of a very large file (such as `src/js/core.js`) will not fit in your output, do not send a partial file. Instead list exact find-and-replace edits under `## Edits to apply` (file, exact old text, exact new text).

%s

## 4. Complete Codebase

### Manifest

| File | Lines | Bytes | SHA-256 (first 12) |
|---|---|---|---|
%s

%s
### Binary files

These are the app icons, unchanged unless noted. `tools/apply_handoff.py` decodes them.

%s
""" % (now, sh("git", "rev-parse", "--short", "HEAD"), sh("git", "log", "-1", "--format=%cs %s"), version(), len(fl), len(bins), format(total, ","), state, "\n".join(rows), "\n".join(blocks), "\n".join(bins))
    with open(dest, "w", encoding="utf-8") as fh: fh.write(doc)
    print("wrote", dest, format(len(doc.encode()), ","), "bytes,", len(fl), "text files,", len(bins), "binary")

def version():
    try:
        m = re.search(r'V60_VERSION="([^"]+)"', open(os.path.join(ROOT, "index.html"), encoding="utf-8").read())
        return m.group(1) if m else "unknown"
    except Exception: return "unknown"

if __name__ == "__main__":
    main()
